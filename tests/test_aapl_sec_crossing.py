"""
The AAPL FY2025 10-K crossing, end to end over the real admission.

The facts below are the ones Apple's FY2025 Form 10-K reported, read from
the filing's own XBRL and from the filing's own rendered statement:

  https://www.sec.gov/Archives/edgar/data/320193/000032019325000079/aapl-20250927.htm

  CIK          0000320193
  accession    0000320193-25-000079
  form         10-K
  filed        2025-10-31, accepted 2025-10-31T14:01:26Z
  period       2024-09-29 .. 2025-09-27

  operating income                                    133,050 million USD
  depreciation and amortization                         11,698 million USD
  cash generated by operating activities              111,482 million USD
  payments for acquisition of property, plant and
    equipment                                          12,715 million USD

The tests use the real archive, the real registry and the real admission. The
figures are fixtures because the test must not depend on the SEC being
reachable; they are the filing's own figures and carry the filing's own
provenance, so the admission decides on the same evidence the live run does.

One point of fact is recorded here because the D&A mapping depends on it.
Apple's cash-flow statement carries one line, labelled "Depreciation and
amortization", on the element `us-gaap:DepreciationDepletionAndAmortization`.
The element's own definition also covers depleting assets, so it is not the
pure element, and Apple has no company-specific element for the line. The
registry therefore declares the mapping for Apple alone, scoped to the
issuer, rather than as a market-wide exact mapping.
"""
