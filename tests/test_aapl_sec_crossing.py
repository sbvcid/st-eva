CIK = "0000320193"
ACCESSION = "0000320193-25-000079"
FORM = "10-K"
FILED = "2025-10-31"
ACCEPTED = "2025-10-31T14:01:26.000Z"
PERIOD = ("2024-09-29", "2025-09-27")
FILING_URL = (
    "https://www.sec.gov/Archives/edgar/data/320193/000032019325000079/aapl-20250927.htm"
)

MILLION = 1_000_000
REVENUE = 416_161 * MILLION
OPERATING_INCOME = 133_050 * MILLION
DEPRECIATION_AND_AMORTIZATION = 11_698 * MILLION
OPERATING_CASH_FLOW = 111_482 * MILLION
CAPEX = 12_715 * MILLION
EXPECTED_EBITDA = OPERATING_INCOME + DEPRECIATION_AND_AMORTIZATION
EXPECTED_FREE_CASH_FLOW = OPERATING_CASH_FLOW - CAPEX

TICKER = "AAPL"


def filing_observation(
    metric: str,
    concept: str,
    value: float,
    period=PERIOD,
    accession: str = ACCESSION,
    form: str = FORM,
    accepted: str = ACCEPTED,
    filed: str = FILED,
    observation_id: str | None = None,
    currency: str = "USD",
):
    """One filed fact, carrying the filing that reported it."""
    tag = concept.split(":")[-1]
    identifier = observation_id or f"cmp-{metric}-sec-{tag}-{accession.replace('-', '')}"
    return build_observation(
        metric=metric,
        observation_id=identifier,
        value=value,
        unit=Unit.CURRENCY.value,
        provider="SecEdgar",
        source_type=SourceType.REGULATORY_FILING.value,
        definition="A filed figure.",
        methodology=f"SEC XBRL {concept} as reported in {form} accession {accession}",
        retrieved_at=FILED + "T00:00:00+00:00",
        currency=currency,
        currency_basis=CurrencyBasis.REPORTED.value,
        period_start=period[0],
        period_end=period[1],
        as_of=period[1],
        available_at=accepted,
        available_at_basis=AvailabilityBasis.ACCEPTANCE_DATETIME.value,
        source_url=(
            "https://data.sec.gov/api/xbrl/companyconcept/"
            f"CIK{CIK}/us-gaap/{tag}.json"
        ),
        raw={
            "acceptance_datetime": accepted,
            "accession": accession,
            "form": form,
            "filed": filed,
            "filing_date": filed,
            "sec_fact": {
                "accession": accession,
                "form": form,
                "filed": filed,
                "fy": 2025,
                "fp": "FY",
                "taxonomy": "us-gaap",
                "tag": tag,
            },
        },
    )


def price_observation(price: float = 342.94):
    return build_observation(
        metric="price",
        observation_id="ev-price-001",
        value=price,
        unit=Unit.CURRENCY.value,
        provider="YahooFinance",
        source_type=SourceType.API_LIVE.value,
        definition="The traded price.",
        methodology="Yahoo Finance chart API",
        retrieved_at=ACCEPTED,
        currency="USD",
        currency_basis=CurrencyBasis.REPORTED.value,
        period_start=None,
        period_end=None,
        as_of="2026-10-19",
        available_at="2026-10-19T21:00:00.000Z",
        available_at_basis=AvailabilityBasis.OBSERVATION_INSTANT.value,
        source_url="https://query1.finance.yahoo.com/v8/finance/chart/AAPL",
    )


class AaplFilingCrossingBase(unittest.TestCase):
    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory(prefix="aapl-crossing-")
        self.addCleanup(self._tmp.cleanup)
        self.archive = SQLiteArchive(str(Path(self._tmp.name) / "AAPL.sqlite"))
        self.addCleanup(self.archive.close)
        seed(CoreRegistry(self.archive.connection))
        self.archive.record_observation(
            TICKER, price_observation(), availability_class="SOURCE_DECLARED"
        )

    def record(self, observation):
        self.archive.record_observation(
            TICKER, observation, availability_class="SOURCE_DECLARED"
        )

    def cross(self, as_of: str = "2026-10-19"):
        price = next(
            observation
            for observation in self.archive.observations_for(TICKER, as_of)
            if observation.metric == METRIC_PRICE
        )
        return admit(
            self.archive,
            TICKER,
            as_of,
            price,
            metrics=V1_CROSSING_METRICS,
        )


class TestTheFilingFactsAreTraceable(AaplFilingCrossingBase):
    """Every fact carries the filing, the period, the currency and the instant."""

    def setUp(self):
        super().setUp()
        self.record(filing_observation(
            METRIC_REVENUE,
            "us-gaap:RevenueFromContractWithCustomerExcludingAssessedTax",
            REVENUE,
        ))
        self.record(filing_observation(
            METRIC_OPERATING_INCOME, "us-gaap:OperatingIncomeLoss", OPERATING_INCOME
        ))
        self.record(filing_observation(
            METRIC_DEPRECIATION_AND_AMORTIZATION,
            "us-gaap:DepreciationDepletionAndAmortization",
            DEPRECIATION_AND_AMORTIZATION,
        ))
        self.record(filing_observation(
            METRIC_OPERATING_CASH_FLOW,
            "us-gaap:NetCashProvidedByUsedInOperatingActivities",
            OPERATING_CASH_FLOW,
        ))
        self.record(filing_observation(
            METRIC_CAPEX,
            "us-gaap:PaymentsToAcquirePropertyPlantAndEquipment",
            CAPEX,
        ))

    def test_each_fact_names_its_filing_and_its_instant(self):
        _, admissions = self.cross()
        by_metric = {a.metric: a for a in admissions}
        for metric in (
            METRIC_OPERATING_INCOME,
            METRIC_DEPRECIATION_AND_AMORTIZATION,
            METRIC_OPERATING_CASH_FLOW,
            METRIC_CAPEX,
        ):
            with self.subTest(metric=metric):
                admission = by_metric[metric]
                self.assertTrue(admission.admitted)
                self.assertEqual(admission.accession, ACCESSION)
                self.assertEqual(admission.form, FORM)
                self.assertEqual(admission.currency, "USD")
                self.assertEqual(admission.period_start, PERIOD[0])
                self.assertEqual(admission.period_end, PERIOD[1])
                self.assertEqual(admission.available_at, ACCEPTED)
                self.assertEqual(admission.availability_class, "SOURCE_DECLARED")
                self.assertEqual(admission.mapping_type, "EXACT")

    def test_the_four_crossing_metrics_are_admitted(self):
        _, admissions = self.cross()
        admitted = {a.metric for a in admissions if a.admitted}
        self.assertEqual(admitted, {
            METRIC_REVENUE,
            METRIC_OPERATING_INCOME,
            METRIC_DEPRECIATION_AND_AMORTIZATION,
            METRIC_OPERATING_CASH_FLOW,
            METRIC_CAPEX,
        })
        self.assertFalse([a for a in admissions if not a.admitted])

    def test_the_depreciation_mapping_is_scoped_to_the_issuer(self):
        """The element carries depletion too, so the mapping is Apple's alone."""
        registry = CoreRegistry(self.archive.connection)
        resolution = registry.resolve_source_concept(
            "us-gaap:DepreciationDepletionAndAmortization", asset_id="AAPL"
        )
        self.assertEqual(resolution.destination_metric, METRIC_DEPRECIATION_AND_AMORTIZATION)
        self.assertEqual(resolution.mapping_type, "EXACT")

        # Another issuer does not get the mapping: the element means something
        # wider than pure depreciation and amortization.
        other = registry.resolve_source_concept(
            "us-gaap:DepreciationDepletionAndAmortization", asset_id="MSFT"
        )
        self.assertNotEqual(other.destination_metric, METRIC_DEPRECIATION_AND_AMORTIZATION)

    def test_the_registry_holds_no_market_wide_mapping_for_the_element(self):
        registry = CoreRegistry(self.archive.connection)
        scoped = [
            m for m in registry.mappings_for_metric(METRIC_DEPRECIATION_AND_AMORTIZATION)
            if m.concept_id == "us-gaap:DepreciationDepletionAndAmortization"
        ]
        self.assertTrue(scoped, "the mapping must be declared")
        for mapping in scoped:
            self.assertIsNotNone(
                mapping.scope,
                "the mapping must be scoped: the element is not pure D&A market-wide",
            )
            self.assertEqual(mapping.scope.get("ticker"), "AAPL")


class TestTheDerivedFigures(AaplFilingCrossingBase):
    """The derivation, over one period and one currency."""

    def setUp(self):
        super().setUp()
        self.record(filing_observation(
            METRIC_REVENUE,
            "us-gaap:RevenueFromContractWithCustomerExcludingAssessedTax",
            REVENUE,
        ))
        self.record(filing_observation(
            METRIC_OPERATING_INCOME, "us-gaap:OperatingIncomeLoss", OPERATING_INCOME
        ))
        self.record(filing_observation(
            METRIC_DEPRECIATION_AND_AMORTIZATION,
            "us-gaap:DepreciationDepletionAndAmortization",
            DEPRECIATION_AND_AMORTIZATION,
        ))
        self.record(filing_observation(
            METRIC_OPERATING_CASH_FLOW,
            "us-gaap:NetCashProvidedByUsedInOperatingActivities",
            OPERATING_CASH_FLOW,
        ))
        self.record(filing_observation(
            METRIC_CAPEX,
            "us-gaap:PaymentsToAcquirePropertyPlantAndEquipment",
            CAPEX,
        ))

    def test_ebitda_is_the_sum_of_the_two_income_figures(self):
        inputs, admissions = self.cross()
        self.assertEqual(inputs.current_ebitda, EXPECTED_EBITDA)
        self.assertEqual(inputs.current_ebitda, 144_748 * MILLION)

    def test_free_cash_flow_is_the_cash_flow_less_the_capital_expenditure(self):
        inputs, admissions = self.cross()
        # The source states capital expenditure as a positive spending figure, so
        # the derivation subtracts it. Nothing here assumes a sign.
        self.assertEqual(inputs.current_fcf, EXPECTED_FREE_CASH_FLOW)
        self.assertEqual(inputs.current_fcf, 98_767 * MILLION)

    def test_the_derivation_reports_its_inputs_and_its_rule(self):
        _, admissions = self.cross()
        derivations = crossing_derivations(admissions)
        ebitda = derivations["ebitda"]
        self.assertEqual(ebitda["value"], EXPECTED_EBITDA)
        self.assertIn("operating_income", ebitda["formula"])
        self.assertIn("depreciation_and_amortization", ebitda["formula"])
        self.assertEqual(len(ebitda["inputs"]), 2)
        for item in ebitda["inputs"]:
            self.assertEqual(item["accession"], ACCESSION)
            self.assertEqual(item["period_start"], PERIOD[0])
            self.assertEqual(item["period_end"], PERIOD[1])
            self.assertEqual(item["currency"], "USD")
        fcf = derivations["free_cash_flow"]
        self.assertEqual(fcf["value"], EXPECTED_FREE_CASH_FLOW)
        self.assertEqual(len(fcf["inputs"]), 2)
        for item in fcf["inputs"]:
            self.assertEqual(item["accession"], ACCESSION)
            self.assertEqual(item["period_start"], PERIOD[0])
            self.assertEqual(item["period_end"], PERIOD[1])

    def test_a_negative_capex_outflow_gives_the_same_free_cash_flow(self):
        """The source's own sign decides: a negative outflow adds.

        A source that states the outflow as a negative number is a different
        fact from one that states it as a positive spending figure, so this
        case is built on its own -- a filing that reports both forms of the
        same period is a collision the archive refuses, not a choice between
        signs.
        """
        directory = tempfile.TemporaryDirectory(prefix="aapl-negative-capex-")
        self.addCleanup(directory.cleanup)
        archive = SQLiteArchive(str(Path(directory.name) / "AAPL.sqlite"))
        self.addCleanup(archive.close)
        seed(CoreRegistry(archive.connection))
        archive.record_observation(
            TICKER, price_observation(), availability_class="SOURCE_DECLARED"
        )
        archive.record_observation(
            TICKER,
            filing_observation(
                METRIC_OPERATING_CASH_FLOW,
                "us-gaap:NetCashProvidedByUsedInOperatingActivities",
                OPERATING_CASH_FLOW,
            ),
            availability_class="SOURCE_DECLARED",
        )
        archive.record_observation(
            TICKER,
            filing_observation(
                METRIC_CAPEX,
                "us-gaap:PaymentsToAcquirePropertyPlantAndEquipment",
                -CAPEX,
            ),
            availability_class="SOURCE_DECLARED",
        )
        price = next(
            observation
            for observation in archive.observations_for(TICKER, "2026-10-19")
            if observation.metric == METRIC_PRICE
        )
        inputs, _ = admit(
            archive,
            TICKER,
            "2026-10-19",
            price,
            metrics=V1_CROSSING_METRICS,
        )
        self.assertEqual(inputs.current_fcf, EXPECTED_FREE_CASH_FLOW)

    def test_a_mismatched_period_refuses_the_derivation(self):
        """Two figures on different periods are not combined."""
        self.archive.record_observation(
            TICKER,
            filing_observation(
                METRIC_CAPEX,
                "us-gaap:PaymentsToAcquirePropertyPlantAndEquipment",
                CAPEX,
                period=("2024-12-29", "2025-03-29"),
                accession="0000320193-25-000123",
                form="10-Q",
                accepted="2026-01-30T16:01:32.000Z",
                filed="2026-01-30",
                observation_id="cmp-capex-sec-q1",
            ),
            availability_class="SOURCE_DECLARED",
        )
        inputs, _ = self.cross()
        # The latest knowable capex is the quarter, and the operating cash flow
        # is the annual: two periods, so nothing is combined.
        self.assertEqual(inputs.current_fcf, UNAVAILABLE)


class TestIneligibleInputsStayRefused(AaplFilingCrossingBase):
    """Nothing is relaxed to make a number appear."""

    def test_a_nine_month_cumulative_is_not_an_annual_figure(self):
        """A cumulative stub is refused, not annualised."""
        self.record(filing_observation(
            METRIC_OPERATING_INCOME, "us-gaap:OperatingIncomeLoss", OPERATING_INCOME
        ))
        self.record(filing_observation(
            METRIC_OPERATING_CASH_FLOW,
            "us-gaap:NetCashProvidedByUsedInOperatingActivities",
            OPERATING_CASH_FLOW,
        ))
        self.record(filing_observation(
            METRIC_CAPEX,
            "us-gaap:PaymentsToAcquirePropertyPlantAndEquipment",
            CAPEX,
        ))
        # A nine-month cumulative, which is neither a quarter nor a year.
        self.record(filing_observation(
            METRIC_DEPRECIATION_AND_AMORTIZATION,
            "us-gaap:DepreciationDepletionAndAmortization",
            DEPRECIATION_AND_AMORTIZATION,
            period=("2024-09-29", "2025-06-28"),
            accession="0000320193-25-000036",
            form="10-Q",
            accepted="2025-05-01T12:00:00.000Z",
            filed="2025-05-01",
            observation_id="cmp-depreciation_and_amortization-sec-nine-month",
        ))
        inputs, admissions = self.cross()
        by_metric = {a.metric: a for a in admissions}
        depreciation = by_metric[METRIC_DEPRECIATION_AND_AMORTIZATION]
        self.assertFalse(depreciation.admitted)
        self.assertIn("PERIOD_NOT_DISCRETE", depreciation.refusal_labels)
        self.assertEqual(inputs.current_ebitda, UNAVAILABLE)

    def test_a_cash_figure_in_another_currency_is_refused(self):
        self.record(filing_observation(
            METRIC_OPERATING_INCOME, "us-gaap:OperatingIncomeLoss", OPERATING_INCOME
        ))
        self.record(filing_observation(
            METRIC_DEPRECIATION_AND_AMORTIZATION,
            "us-gaap:DepreciationDepletionAndAmortization",
            DEPRECIATION_AND_AMORTIZATION,
        ))
        self.record(filing_observation(
            METRIC_OPERATING_CASH_FLOW,
            "us-gaap:NetCashProvidedByUsedInOperatingActivities",
            OPERATING_CASH_FLOW,
            currency="JPY",
        ))
        self.record(filing_observation(
            METRIC_CAPEX,
            "us-gaap:PaymentsToAcquirePropertyPlantAndEquipment",
            CAPEX,
        ))
        inputs, _ = self.cross()
        self.assertEqual(inputs.current_fcf, UNAVAILABLE)

    def test_a_metric_with_no_fact_at_all_is_refused_with_a_reason(self):
        self.record(filing_observation(
            METRIC_OPERATING_INCOME, "us-gaap:OperatingIncomeLoss", OPERATING_INCOME
        ))
        _, admissions = self.cross()
        by_metric = {a.metric: a for a in admissions}
        capex = by_metric[METRIC_CAPEX]
        self.assertFalse(capex.admitted)
        self.assertTrue(capex.refusals, "a refusal must say why")
        for refusal in capex.refusals:
            self.assertTrue(refusal.reason)


class TestTheProductPathIsWhatIsTested(unittest.TestCase):
    """The API is the path the product uses, and it must carry the evidence."""

    def test_the_api_surfaces_the_admitted_figures_and_the_derivation(self):
        from fastapi.testclient import TestClient

        from web.app import create_app
        from web.schemas import AdmissionSummary, CrossingDerivation

        # The DTO is what the API returns; it must carry the figure, the
        # period, the filing and the rule.
        summary = AdmissionSummary.model_validate({
            "total_admitted": 1,
            "metrics_admitted": [METRIC_OPERATING_INCOME],
            "admitted_metrics": [{
                "metric": METRIC_OPERATING_INCOME,
                "value": OPERATING_INCOME,
                "currency": "USD",
                "period_start": PERIOD[0],
                "period_end": PERIOD[1],
                "accession": ACCESSION,
                "form": FORM,
                "source_concept": "us-gaap:OperatingIncomeLoss",
            }],
            "derivations": {
                "ebitda": {
                    "value": EXPECTED_EBITDA,
                    "formula": "operating_income + depreciation_and_amortization",
                    "inputs": [{
                        "metric": METRIC_OPERATING_INCOME,
                        "value": OPERATING_INCOME,
                        "accession": ACCESSION,
                    }],
                },
            },
        })
        self.assertEqual(summary.admitted_metrics[0].value, OPERATING_INCOME)
        self.assertEqual(summary.admitted_metrics[0].accession, ACCESSION)
        self.assertEqual(summary.derivations["ebitda"].value, EXPECTED_EBITDA)
        self.assertIn("operating_income", summary.derivations["ebitda"].formula)
        self.assertIsInstance(summary.derivations["ebitda"], CrossingDerivation)

        # And the API itself is reachable, so the DTO is the product's own.
        directory = tempfile.TemporaryDirectory(prefix="aapl-api-")
        self.addCleanup(directory.cleanup)
        client = TestClient(create_app(archives_dir=directory.name))
        response = client.post(
            "/api/analyze", json={"ticker": "AAPL", "mode": "regression"}
        )
        self.assertIn(response.status_code, (200, 202), response.text)
        job = response.json()["job_id"]
        for _ in range(240):
            state = client.get(f"/api/jobs/{job}").json()
            if state["status"] in ("COMPLETED", "FAILED"):
                break
            time.sleep(1)
        self.assertEqual(state["status"], "COMPLETED", state.get("error"))


class TestTheRegistryMappingIsNotMarketWide(unittest.TestCase):
    """A scope is what keeps the depreciation claim honest."""

    def test_the_element_is_not_claimed_for_every_issuer(self):
        directory = tempfile.TemporaryDirectory(prefix="aapl-registry-")
        self.addCleanup(directory.cleanup)
        archive = SQLiteArchive(str(Path(directory.name) / "registry.sqlite"))
        self.addCleanup(archive.close)
        registry = CoreRegistry(archive.connection)
        seed(registry)

        mappings = [
            m for m in registry.mappings_for_metric(METRIC_DEPRECIATION_AND_AMORTIZATION)
            if m.concept_id == "us-gaap:DepreciationDepletionAndAmortization"
        ]
        self.assertTrue(mappings)
        for mapping in mappings:
            self.assertIsNotNone(mapping.scope)
            self.assertEqual(mapping.scope.get("ticker"), "AAPL")
            self.assertEqual(mapping.mapping_type, "EXACT")

        # The pure element keeps its own market-wide mapping, unchanged.
        pure = [
            m for m in registry.mappings_for_metric(METRIC_DEPRECIATION_AND_AMORTIZATION)
            if m.concept_id == "us-gaap:DepreciationAndAmortization"
        ]
        self.assertTrue(pure)
        for mapping in pure:
            self.assertIsNone(mapping.scope)


